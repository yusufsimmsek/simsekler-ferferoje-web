import { describe, expect, it } from "vitest";
import { createProjectFromPrompt } from "@/lib/projects/create-project-client";
import { editGeneratedProjectWithMessage } from "@/lib/projects/edit-project-client";
import { runEditPlanWorkflow } from "@/lib/ai-planner/edit-plan-workflow";
import {
  createEmptyGeneratedProjectStore,
  generatedPlanStorageKey,
  listGeneratedProjects,
  loadGeneratedProject,
  saveGeneratedProject,
  type StorageLike
} from "@/lib/projects/generated-plan-storage";
import {
  createEditorStateFromGeneratedProject,
  createPlaceholderEditorState
} from "@/lib/editor/state";
import { mockFloorPlan } from "@/lib/floor-plan/mock-plan";

describe("create project flow helpers", () => {
  it("stores a generated plan after a successful create API response", async () => {
    const storage = createMemoryStorage();
    const fetcher = async () => ({
      ok: true,
      status: 200,
      json: async () => ({
        ok: true,
        code: "PLAN_GENERATED",
        provider: "mock",
        schemaVersion: "plan-generation-response-v1",
        plan: mockFloorPlan,
        validation: mockFloorPlan.validation,
        warnings: ["Layout generated by deterministic MVP zone-grid engine."],
        meta: {
          mock: true,
          promptClassification: "3plus1",
          classificationReason: "Prompt matched 3+1 apartment language.",
          layoutMode: "layout-engine-v1"
        }
      })
    });

    const result = await createProjectFromPrompt({
      request: {
        prompt: "Create a 3+1 apartment with balcony.",
        projectName: "Client 3+1"
      },
      storage,
      fetcher,
      now: () => "2026-06-18T00:00:00.000Z"
    });

    expect(result.ok).toBe(true);

    if (result.ok) {
      expect(result.project.projectId).toBe(mockFloorPlan.projectId);
      expect(result.project.projectName).toBe("Client 3+1");
      expect(loadGeneratedProject(storage, mockFloorPlan.projectId).ok).toBe(true);
    }
  });

  it("returns a developer-readable error for create API failures", async () => {
    const result = await createProjectFromPrompt({
      request: {
        prompt: "Create a permit-ready 3D BIM model."
      },
      storage: createMemoryStorage(),
      fetcher: async () => ({
        ok: false,
        status: 422,
        json: async () => ({
          ok: false,
          code: "AI_UNSUPPORTED_REQUEST",
          provider: "mock",
          message: "This MVP supports simple 2D rectangular apartment plans only.",
          developerMessage: "Mock provider classified the prompt as unsupported.",
          retryable: false,
          validation: {
            status: "invalid",
            issues: []
          },
          issues: [],
          warnings: ["This MVP supports simple 2D rectangular conceptual apartment plans only."]
        })
      })
    });

    expect(result.ok).toBe(false);

    if (!result.ok) {
      expect(result.code).toBe("API_ERROR");
      expect(result.retryable).toBe(false);
      expect(result.message).toContain("2D rectangular");
    }
  });

  it("handles generated plan state for the editor", () => {
    const project = {
      projectId: mockFloorPlan.projectId,
      projectName: "Stored concept",
      plan: mockFloorPlan,
      prompt: "Create a 3+1 apartment.",
      aiSummary: "Prompt matched 3+1 apartment language.",
      warnings: ["Mock warning"],
      createdAt: "2026-06-18T00:00:00.000Z"
    };
    const state = createEditorStateFromGeneratedProject(project);

    expect(state.plan?.id).toBe(mockFloorPlan.id);
    expect(state.projectName).toBe("Stored concept");
    expect(state.projectPrompt).toBe("Create a 3+1 apartment.");
    expect(state.fallbackReason).toBeNull();
    expect(state.warnings).toContain("Mock warning");
  });

  it("falls back to the demo plan when temporary storage has no generated project", () => {
    const missing = loadGeneratedProject(createMemoryStorage(), "missing_project");
    const fallback = createPlaceholderEditorState("missing_project");

    expect(missing.ok).toBe(false);

    if (!missing.ok) {
      expect(missing.fallback).toBe(true);
      expect(missing.message).toContain("No generated project");
    }

    expect(fallback.plan?.id).toBe(mockFloorPlan.id);
    expect(fallback.fallbackReason).toContain("No generated project");
  });

  it("can save and load generated project storage directly", () => {
    const storage = createMemoryStorage();
    const project = {
      projectId: mockFloorPlan.projectId,
      projectName: null,
      plan: mockFloorPlan,
      prompt: "Create a 3+1 apartment.",
      aiSummary: "Prompt matched 3+1 apartment language.",
      warnings: [],
      createdAt: "2026-06-18T00:00:00.000Z"
    };

    expect(createEmptyGeneratedProjectStore().lastProjectId).toBeNull();
    saveGeneratedProject(storage, project);

    const loaded = loadGeneratedProject(storage, mockFloorPlan.projectId);

    expect(loaded.ok).toBe(true);

    if (loaded.ok) {
      expect(loaded.project.plan.id).toBe(mockFloorPlan.id);
    }
  });

  it("loads old stored projects without optional metadata", () => {
    const storage = createMemoryStorage();
    const legacyProject = {
      projectId: mockFloorPlan.projectId,
      projectName: null,
      plan: mockFloorPlan,
      prompt: "Create a legacy 3+1 apartment.",
      aiSummary: "Legacy project without metadata.",
      warnings: [],
      createdAt: "2026-06-18T00:00:00.000Z"
    };

    storage.setItem(
      generatedPlanStorageKey,
      JSON.stringify({
        version: 1,
        projects: {
          [legacyProject.projectId]: legacyProject
        },
        lastProjectId: legacyProject.projectId
      })
    );

    const loaded = loadGeneratedProject(storage, mockFloorPlan.projectId);

    expect(loaded.ok).toBe(true);

    if (loaded.ok) {
      expect(loaded.project.metadata).toBeUndefined();
      expect(loaded.project.plan.id).toBe(mockFloorPlan.id);
    }
  });

  it("stores latest edit quality metadata after a successful chat edit", async () => {
    const storage = createMemoryStorage();
    const project = {
      projectId: mockFloorPlan.projectId,
      projectName: null,
      plan: mockFloorPlan,
      prompt: "Create a 3+1 apartment.",
      aiSummary: "Initial generated plan.",
      warnings: [],
      createdAt: "2026-06-18T00:00:00.000Z"
    };
    const editResult = await runEditPlanWorkflow({
      schemaVersion: "plan-edit-request-v1",
      message: "Make the living room larger.",
      currentPlan: mockFloorPlan
    });

    expect(editResult.body.ok).toBe(true);

    if (!editResult.body.ok) {
      throw new Error(editResult.body.developerMessage);
    }

    const result = await editGeneratedProjectWithMessage({
      request: {
        message: "Make the living room larger.",
        project
      },
      storage,
      fetcher: async () => ({
        ok: true,
        status: 200,
        json: async () => editResult.body
      })
    });

    expect(result.ok).toBe(true);

    if (result.ok) {
      expect(result.project.metadata?.lastEditQualityDelta?.schemaVersion).toBe(
        "edit-quality-delta-v1"
      );
      expect(result.project.metadata?.quality?.schemaVersion).toBe(
        "layout-quality-report-v1"
      );
      expect(loadGeneratedProject(storage, mockFloorPlan.projectId).ok).toBe(
        true
      );
    }
  });

  it("lists validated local projects for the dashboard in newest-first order", () => {
    const storage = createMemoryStorage();
    const olderProject = {
      projectId: "project_older",
      projectName: "Older concept",
      plan: {
        ...mockFloorPlan,
        projectId: "project_older"
      },
      prompt: "Create an older 3+1 apartment.",
      aiSummary: "Older project",
      warnings: [],
      createdAt: "2026-06-17T00:00:00.000Z"
    };
    const newerProject = {
      ...olderProject,
      projectId: "project_newer",
      projectName: "Newer concept",
      plan: {
        ...mockFloorPlan,
        projectId: "project_newer"
      },
      createdAt: "2026-06-19T00:00:00.000Z"
    };

    saveGeneratedProject(storage, olderProject);
    saveGeneratedProject(storage, newerProject);

    const result = listGeneratedProjects(storage);

    expect(result.message).toBeNull();
    expect(result.projects.map((project) => project.projectId)).toEqual([
      "project_newer",
      "project_older"
    ]);
  });
});

function createMemoryStorage(): StorageLike {
  const data = new Map<string, string>();

  return {
    getItem: (key) => data.get(key) ?? null,
    setItem: (key, value) => {
      data.set(key, value);
    },
    removeItem: (key) => {
      data.delete(key);
    }
  };
}
