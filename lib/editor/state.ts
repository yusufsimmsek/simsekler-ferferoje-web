import { mockFloorPlan } from "@/lib/floor-plan/mock-plan";
import type { StoredGeneratedProject } from "@/lib/projects/generated-plan-storage";
import type { EditorState } from "./types";

export function createPlaceholderEditorState(projectId = "project_mock_001"): EditorState {
  return {
    mode: "ready",
    projectId,
    projectName: null,
    plan: mockFloorPlan,
    messages: [
      {
        id: "msg_system_mock",
        role: "system",
        content: "Mock mode is active. Real AI planning will be connected later."
      }
    ],
    selectedRoomId: "room_living",
    validationIssues: mockFloorPlan.validation.issues,
    warnings: mockFloorPlan.layout.warnings ?? [],
    projectPrompt: mockFloorPlan.metadata.promptSummary,
    aiSummary: "Demo fallback plan generated by the deterministic mock layout pipeline.",
    fallbackReason: "No generated project was found in temporary browser storage.",
    mockMode: true
  };
}

export function createEditorStateFromGeneratedProject(
  project: StoredGeneratedProject
): EditorState {
  return {
    mode: "ready",
    projectId: project.projectId,
    projectName: project.projectName,
    plan: project.plan,
    messages: [
      {
        id: "msg_system_generated",
        role: "system",
        content: "Generated mock plan loaded from temporary browser storage."
      }
    ],
    selectedRoomId: project.plan.rooms.find((room) => room.type === "living")?.id ?? project.plan.rooms[0]?.id ?? null,
    validationIssues: project.plan.validation.issues,
    warnings: uniqueWarnings([
      ...project.warnings,
      ...(project.plan.layout.warnings ?? []),
      ...project.plan.validation.issues.map((issue) => issue.message)
    ]),
    projectPrompt: project.prompt,
    aiSummary: project.aiSummary,
    fallbackReason: null,
    mockMode: true
  };
}

function uniqueWarnings(warnings: string[]) {
  return Array.from(new Set(warnings.filter((warning) => warning.trim().length > 0)));
}
